    def test_generate_points_fibonacci_lattice_no_poles(self):
        """
        Test that no generated Fibonacci lattice point sits exactly at
        either pole, per Gonzalez (2010)'s construction (referenced in the
        function's docstring).
        """
        points = generate_points_fibonacci_lattice(2000000)
        self.assertTrue((points.geometry.y.abs() < 90).all())

    def test_generate_points_fibonacci_lattice_matches_published_formula(self):
        """
        Test the first and last (by index) Fibonacci lattice point
        latitudes against Gonzalez (2010)'s closed-form placement formula,
        computed independently here rather than by importing the
        implementation's private helper.
        """
        distance = 2000000
        points = generate_points_fibonacci_lattice(distance)
        n = len(points)
        expected_first_latitude = np.degrees(np.arcsin(2 * 1 / (n + 2) - 1))
        expected_last_latitude = np.degrees(np.arcsin(2 * n / (n + 2) - 1))
        points_by_id = points.set_index("point_id")
        self.assertAlmostEqual(
            points_by_id.loc[0].geometry.y, expected_first_latitude, places=9
        )
        self.assertAlmostEqual(
            points_by_id.loc[n - 1].geometry.y, expected_last_latitude, places=9
        )

    def test_generate_points_fibonacci_lattice_antimeridian_crossing_mask(self):
        """
        Test the Fibonacci lattice generator with a mask crossing the
        antimeridian expressed in unwrapped longitude (170 to 190 degrees,
        rather than 170 to -170). All returned points should fall within
        the mask's own [170, 190] longitude convention -- including points
        whose natural longitude is negative (e.g. -175), which the
        implementation shifts by +360 to match the mask's unwrapped frame
        -- rather than being wrapped back to the standard [-180, 180]
        range.
        """
        mask = Polygon([[170, -10], [190, -10], [190, 10], [170, 10], [170, -10]])
        points = generate_points_fibonacci_lattice(500000, mask=mask)
        self.assertGreater(len(points), 0)
        self.assertTrue((points.geometry.x >= 170).all())
        self.assertTrue((points.geometry.x <= 190).all())
        # confirms points originally at negative longitude were included
        # via the +360 shift, not dropped
        self.assertTrue((points.geometry.x > 180).any())

    def test_generate_points_uniform_angular_distance_point_id_matches_grid_formula(
        self,
    ):
        """
        Test that every point_id returned by the equally spaced generator
        matches compute_point_id_uniform_spacing for that point's
        recovered (i, j) grid index, confirming point_id is a stable,
        dense (no gaps or collisions) enumeration for a global grid.
        """
        theta = 10
        points = generate_points_uniform_angular_distance(theta, theta)
        self.assertEqual(sorted(points.point_id), list(range(len(points))))
        for _, row in points.iterrows():
            i = round((row.geometry.x - (-180 + 0.5 * theta)) / theta)
            j = round((row.geometry.y - (-90 + 0.5 * theta)) / theta)
            self.assertEqual(
                compute_point_id_uniform_spacing(i, j, theta), row.point_id
            )
