import unittest

import numpy as np
import pyproj
from shapely.geometry import Polygon
from shapely.ops import transform

from tatc import constants, utils
from tatc.generation import (
    generate_points_fibonacci_lattice,
    generate_points_uniform_angular_distance,
    generate_points_uniform_spacing,
)
from tatc.generation._grid import compute_point_id_uniform_spacing


class TestPointGenerators(unittest.TestCase):
    """
    Unit tests for the point generation functions in tatc.generation.
    """

    def test_generate_points_fibonacci_lattice_no_mask_count(self):
        """
        Test that the number of points generated by the Fibonacci lattice generator is correct.
        """
        distance = 2000000
        points = generate_points_fibonacci_lattice(distance)
        num_samples = utils.compute_number_samples(distance)
        self.assertEqual(len(points), num_samples)

    def test_generate_equally_spaced_points_no_mask_count(self):
        """
        Test that the number of points generated by the equally spaced generator is correct.
        """
        points = generate_points_uniform_angular_distance(10, 10)
        num_samples = (360 / 10) * (180 / 10)
        self.assertEqual(len(points), num_samples)

    def test_generate_points_fibonacci_lattice_no_mask_distance(self):
        """
        Test that the mean distance between points generated by the
        Fibonacci lattice generator is correct.
        """
        distance = 2000000
        points = generate_points_fibonacci_lattice(distance)
        test_points_m = points.to_crs("EPSG:32663")
        test_points_m["closest_neighbor"] = test_points_m.apply(
            lambda r: test_points_m[test_points_m.point_id != r.point_id]
            .distance(r.geometry)
            .min(),
            axis=1,
        )
        # mean should be within 10% of target sample distance
        self.assertAlmostEqual(
            test_points_m.closest_neighbor.mean(),
            distance,
            delta=0.10 * distance,
        )

    def test_generate_points_fibonacci_lattice_mask_count(self):
        """
        Test that the number of points generated by the Fibonacci
        lattice generator with a mask is correct.
        """
        distance = 2000000
        mask = Polygon([[-100, 25], [-50, 25], [-50, -25], [-100, -25], [-100, 25]])
        points = generate_points_fibonacci_lattice(distance, mask=mask)
        num_samples = utils.compute_number_samples(distance)
        transformer = pyproj.Transformer.from_crs(
            pyproj.CRS("EPSG:4326"), pyproj.CRS("EPSG:32663"), always_xy=True
        ).transform
        mask_m = transform(transformer, mask)
        self.assertAlmostEqual(
            len(points),
            int(num_samples * mask_m.area / constants.EARTH_SURFACE_AREA),
            delta=1,
        )

