def _load_page_script(name):
    spec = importlib.util.spec_from_file_location(name, _VALIDATION / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


